// Builds what the site serves to agents. Runs before `next dev` and `next build`.
//   content/*.md            → content/generated.ts (bundled, so no route reads the filesystem)
//   ../../skills/ghost-record → public/skills/ghost-record
//   ../../packages/ghost-cursor → public/ghost-cursor.tgz (npm pack, for installs before the npm release)
import { execFileSync } from "node:child_process";
import { cp, mkdir, readdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { basename, join, resolve } from "node:path";

const site = resolve(import.meta.dirname, "..");
const repo = resolve(site, "../..");

const content = join(site, "content");
const pages = {};
for (const file of (await readdir(content)).filter((f) => f.endsWith(".md")).sort()) {
  pages[basename(file, ".md")] = await readFile(join(content, file), "utf8");
}
await writeFile(
  join(content, "generated.ts"),
  `// Generated by scripts/prepare-agent-assets.mjs from content/*.md. Edit the .md files.\nexport const pages = ${JSON.stringify(pages, null, 2)} as const;\n`,
);

const skillOut = join(site, "public", "skills", "ghost-record");
await rm(skillOut, { recursive: true, force: true });
await mkdir(skillOut, { recursive: true });
await cp(join(repo, "skills", "ghost-record"), skillOut, { recursive: true });

const pkg = join(repo, "packages", "ghost-cursor");
execFileSync("npm", ["run", "build", "--silent"], { cwd: pkg, stdio: ["ignore", "ignore", "inherit"] });
const out = JSON.parse(
  execFileSync("npm", ["pack", pkg, "--pack-destination", join(site, "public"), "--json", "--silent", "--ignore-scripts"], {
    cwd: site,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "inherit"],
  }),
);
await rename(join(site, "public", out[0].filename), join(site, "public", "ghost-cursor.tgz"));

console.log(`agent assets: ${Object.keys(pages).length} pages, skill, ghost-cursor.tgz (${out[0].version})`);
